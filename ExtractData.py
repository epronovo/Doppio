    args = parser.parse_args()

    defaults = load_user_defaults()
    save_user_defaults(defaults)

    start_time = time.time()
    token = get_ion_token()
    
    # Setup Session
    session = requests.Session()
    session.headers.update({
        "Authorization": f"Bearer {token}",
        "Accept": "application/json",
        "Content-Type": "application/json"
    })

    # The Generator Query
    generator_sql = """
    WITH LowestSequenceCols AS (
        SELECT 
            TableName, 
            ColumnName,
            MIN(sequence) -- This identifies the lowest ID (e.g., 709 vs 710)
        FROM m3TableCols
        WHERE Indexes LIKE '00%' 
        AND ColumnName NOT LIKE '%CONO'
        GROUP BY TableName
    )
    SELECT 
        a.TableName,
        GROUP_CONCAT(DISTINCT a.TableColumn) || ' from ' || a.TableName || '00 where ' || b.ColumnName || ' <> abc' AS GeneratedSQL
    FROM HerffJones_Mapping_Guide a
    LEFT JOIN LowestSequenceCols b ON b.TableName = a.TableName
    WHERE a.TableName IN (SELECT DISTINCT TableName FROM HerffJones_Mapping_Guide WHERE TableName <> '') 
    AND LOWER(a.Mapped) = 'yes'
    GROUP BY a.TableName;
    """

    with sqlite3.connect(SQLITE_DB_PATH) as conn:
        cur = conn.cursor()

        print("🔍 Fetching table mappings from SQLite...")
        cur.execute(generator_sql)
        tables_to_process = cur.fetchall()

        # Track table names and record counts for summary
        table_summary = []

        for table_name, generated_sql in tables_to_process:
            try:
                record_count = process_dynamic_query(cur, table_name, generated_sql, session)
                table_summary.append({
                    'Table Name': table_name,
                    'Records': record_count
                })
            except Exception as e:
                print(f"❌ Error processing {table_name}: {e}")
                table_summary.append({
                    'Table Name': table_name,
                    'Records': 0
                })

        # Export to Excel
        if table_summary:
            date_str = datetime.now().strftime("%Y%m%d")
            # Extract tenant name from path if it's a path
            tenant = CONFIG['tenant']
            if isinstance(tenant, Path):
                tenant_name = tenant.stem
            elif '/' in str(tenant) or '\\' in str(tenant):
                tenant_name = Path(tenant).stem
            else:
                tenant_name = str(tenant)

            company_name = CONFIG.get('company', 'Unknown')
            output_file = BASE_DIR / f"M3_Data_Export_{tenant_name}_{company_name}_{date_str}.xlsx"
            export_to_excel(conn, table_summary, output_file, summary_only=args.summary_only)

    # Timing logic
    elapsed = time.time() - start_time
    hours, rem = divmod(elapsed, 3600)
    minutes, seconds = divmod(rem, 60)
    print(f"\n✅ All tasks complete. Total run time: {int(hours):02d}:{int(minutes):02d}:{int(seconds):02d}")