SELECT DISTINCT
'088'[DIVI],'231'[DONR],printf('%05d', caml.CUNO)[PRF1],printf('%05d', caml.ADID)[PRF2],SUBSTRING(s.CNAM05,1,15)[TX15],s.CNAM05[TX40]
,caml.CUSN05,caml.DSEQ05
FROM CAML_CustomerAddressMaster caml 
JOIN SLP05 s ON s.CUSN05 = caml.CUSN05 AND s.DSEQ05 = caml.DSEQ05
LEFT JOIN AUXADR_CONT1 ON CUSNAU = caml.CUSN05 AND DSEQAU = caml.DSEQ05
UNION
SELECT DISTINCT
'088'[DIVI],'380'[DONR],printf('%05d', caml.CUNO)[PRF1],printf('%05d', caml.ADID)[PRF2],SUBSTRING(s.CNAM05,1,15)[TX15],s.CNAM05[TX40]
,caml.CUSN05,caml.DSEQ05
FROM CAML_CustomerAddressMaster caml 
JOIN SLP05 s ON s.CUSN05 = caml.CUSN05 AND s.DSEQ05 = caml.DSEQ05
LEFT JOIN AUXADR_INVB1 ON CUSNAU = caml.CUSN05 AND DSEQAU = '000' AND TYPEAU='C'
ORDER BY 1,2,3,4
