SELECT 
    TRIM(TTYP40) AS TTYP40,
    TRIM(SUBSTR(TREF40, 1, LOCATE(' ', TREF40 || ' ') - 1)) AS TREF40_1,
    TRIM(SUBSTR(TREF40 || ' ', LOCATE(' ', TREF40 || ' ') + 1)) AS TREF40_2,
    TRIM(TLNO40) AS TLNO40,
    TRIM(TLIN40) AS TLIN40
FROM OSL@@F3.INP40
WHERE USGC40 = 'I'
  AND CONO40 = '88'
  AND TREF40 IS NOT NULL
  AND TREF40 IN (SELECT substr(CUSN05 || '        ', 1, 8) || DSEQ05 FROM sqlite.CAML_CustomerAddressMaster)