SELECT DISTINCT
	TRIM(TTYP40) AS TTYP40,
	TRIM(SUBSTR(TREF40, 1, 7)) AS TREF40_1,
	TRIM(SUBSTR(TREF40, 9, 3)) AS TREF40_2,
	TRIM(TLNO40) AS TLNO40,
	TRIM(TLIN40) AS TLIN40,
	TRIM(USGC40) AS USGC40
FROM OSL@@F3.INP40
WHERE TTYP40 = 'O'
	AND CONO40 = '88'
	AND TREF40 IN (SELECT DISTINCT ORDN55 FROM sqlite.OCOU_Summary)