SELECT
	TRIM(ORDN40) AS ORDN40,
	TRIM(CUSN40) AS CUSN40,
	TRIM(DSEQ40) AS DSEQ40,
	TRIM(CUSO40) AS CUSO40,
	TRIM(DTCO40) AS DTCO40,
	TRIM(DTDR40) AS DTDR40,
	TRIM(CURN40) AS CURN40,
	TRIM(SLMN40) AS SLMN40,
	TRIM(DTSO40) AS DTSO40
FROM
	OSL@@F3.OEP40
WHERE 
	CONO40 = '88'
	AND ORDN40 IN (SELECT DISTINCT ORDN55 FROM sqlite.OCOU_Summary)