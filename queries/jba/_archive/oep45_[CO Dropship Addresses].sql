	TRIM(CONO45) AS CONO45,
	TRIM(ORDN45) AS ORDN45,
	TRIM(SEQN45) AS SEQN45,
	TRIM(ONAM45) AS ONAM45,
	TRIM(OAD145) AS OAD145,
	TRIM(OAD245) AS OAD245,
	TRIM(OAD345) AS OAD345,
	TRIM(OAD445) AS OAD445,
	TRIM(OAD545) AS OAD545,
	TRIM(OPST45) AS OPST45
FROM
	OSL@@F3.OEP45
WHERE 
	CONO45 = '88'
	AND ORDN45 IN (SELECT DISTINCT ORDN55 FROM sqlite.OCOU_Summary)