SELECT
	TRIM(CONO55) AS CONO55,
	TRIM(ORDN55) AS ORDN55,
	TRIM(ORDL55) AS ORDL55,
	TRIM(CUSN55) AS CUSN55,
	TRIM(DSEQ55) AS DSEQ55,
	TRIM(UPRC55) AS UPRC55,
	TRIM(CRQD55) AS CRQD55,
	TRIM(DTDR55) AS DTDR55,
	TRIM(DSDT55) AS DSDT55
FROM
	OSL@@F3.OEP55
WHERE 
	CONO55 = '88'
	AND ORDN55 IN (SELECT DISTINCT ORDN55 FROM sqlite.OCOU_Summary)