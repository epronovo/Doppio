SELECT 
    TRIM(p.SUPN05)  AS SUPN05,
    TRIM(p.DSEQ05)  AS DSEQ05,
    TRIM(SNAM05)    AS SNAM05,
    TRIM(SAD105)    AS SAD105,
    TRIM(SAD205)    AS SAD205,
    TRIM(SAD305)    AS SAD305,
    TRIM(SAD405)    AS SAD405,
    TRIM(SAD505)    AS SAD505,
    TRIM(PCD105)    AS PCD105,
    TRIM(EADD05)    AS EADD05,
    TRIM(EFLG05)    AS EFLG05,
    TRIM(POST05)    AS POST05,
    TRIM(OACT05)    AS OACT05,
    TRIM(PAMT05)    AS PAMT05,
    TRIM(GACT05)    AS GACT05,
    TRIM(LOWER(BAN105)) AS BAN105,
    TRIM(PMTH05) AS PMTH05
FROM OSL@@F3.PLP05 p
LEFT JOIN PRDMODF35.PLP05X x 
    ON x.CONO05 = p.CONO05 
   AND x.SUPN05 = p.SUPN05 
   AND x.DSEQ05 = p.DSEQ05
WHERE RSTS05 = ''
   OR UPPER(TRIM(p.SUPN05)) IN (
       'DUNBAR', 'LIQUASSE', 'ELEMENT', 
       'REECE', 'RENTOHIO', 'SAFKLEEN', 'WAUSEON'
   )
   